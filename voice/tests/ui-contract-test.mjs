import assert from "node:assert/strict";
import { runInNewContext } from "node:vm";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const ui = resolve(import.meta.dirname, "..");
const panel = readFileSync(resolve(ui, "ui/Panel.qml"), "utf8");
const controller = readFileSync(resolve(ui, "ui/VoiceController.qml"), "utf8");
const orb = readFileSync(resolve(ui, "ui/VoiceOrb.qml"), "utf8");
const preview = readFileSync(resolve(ui, "tests/ui-preview.qml"), "utf8");
const manifest = JSON.parse(readFileSync(resolve(ui, "ui/manifest.json"), "utf8"));

assert.equal(manifest.schemaVersion, 1);
assert.equal(manifest.id, "maslow.voice");
assert.deepEqual(manifest.kinds, ["panel"]);
assert.equal(manifest.entryPoints.panel, "Panel.qml");
assert.match(panel, /function open\(payloadJson\)/);
assert.match(panel, /function close\(\)/);
assert.match(panel, /Talk.*Type.*Tasks.*Settings/s);
assert.match(panel, /PanelWindow/);
assert.doesNotMatch(panel, /FloatingWindow/);
assert.match(panel, /mask: Region/);
assert.match(panel, /item: root.controllerOpen \? card : null/);
assert.match(panel, /interactionHeld/);
assert.match(panel, /connecting.*thinking.*listening.*speaking/);
assert.match(panel, /review_id/);
assert.match(panel, /review.changes/);
assert.doesNotMatch(panel, /selectedPath|Please revise the plan/);
for (const key of ["livekit_url", "ollama_models", "speech_directory", "server_url"]) assert.ok(panel.includes(key));
assert.match(panel, /submit_text/);
assert.match(panel, /task_action/);
assert.match(panel, /approval/);
assert.match(panel, /approval_id/);
assert.match(panel, /approval\.request_id/);
assert.match(panel, /credential/);
assert.match(panel, /selectedProject/);
assert.match(panel, /explicitContext/);
assert.match(panel, /does not capture screenshots automatically/);
assert.match(panel, /reduced_motion/);
assert.match(panel, /fixed_position/);
assert.match(controller, /\["omarchy-voice-control", "--watch"\]/);
assert.match(controller, /stdinEnabled: true/);
assert.match(controller, /write\(JSON\.stringify\(value\) \+ "\\n"\)/);
assert.match(controller, /fixtureMode/);
assert.match(orb, /VoiceOrb\.frag\.qsb/);
assert.match(orb, /GraphicsInfo\.Software/);
assert.match(panel, /onSessionLockedChanged/);
assert.match(panel, /serviceFor\("omarchy.lock"\)/);
assert.match(panel, /heldDiameter/);
assert.match(orb, /interactive/);
assert.match(orb, /reducedMotion/);
assert.match(orb, /voiceState === "conversation" \? 88 : 56/);
assert.match(preview, /voiceController\.setFixture/);
const approvalFunction = panel.match(/function needsApproval\(task\) \{[\s\S]*?\n  \}/)[0];
const needsApproval = runInNewContext(`(${approvalFunction})`);
assert.equal(needsApproval({}), false);
assert.equal(needsApproval({ approval: null }), false);
assert.equal(needsApproval({ approval: {} }), false);
assert.equal(needsApproval({ approval: { request_id: "current" } }), true);
const actionFunction = panel.match(/function taskAction\(task, operation, text\) \{[\s\S]*?\n  \}/)[0];
const sent = [];
const context = { send: (action, body) => sent.push({ action, ...body }), feedback: "" };
runInNewContext(`${actionFunction}; taskAction({id:"one", export_review:{digest:"review-v1", changes:[{path:"README.md", action:"modify"}]}}, "export");`, context);
assert.equal(sent[0].review_id, "review-v1");
assert.deepEqual(Array.from(sent[0].paths), ["README.md"]);
runInNewContext(`${actionFunction}; taskAction({id:"one", approval:{}}, "approve");`, context);
assert.equal(sent.length, 1, "Stale approval must not send a request");
assert.ok(context.feedback.includes("stale"));
console.log("Maslow Voice UI contract and approval/export behavior checks passed.");
